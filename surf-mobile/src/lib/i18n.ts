export type I18nKey = keyof (typeof dict)['vi'];

type Params = Record<string, string | number>;

function interpolate(value: string, params?: Params) {
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (_, key: string) =>
    params[key] === undefined ? `{{${key}}}` : String(params[key])
  );
}

export function translate(key: I18nKey, lang: LanguageCode = 'vi', params?: Params) {
  return interpolate(dict[lang][key] ?? dict.vi[key] ?? key, params);
}

export function useT() {
  const language = useSettingsStore((state) => state.prefs.language);
  return useCallback(
    (key: I18nKey, params?: Params) => translate(key, language, params),
    [language]
  );
}

export function useLanguage() {
  return useSettingsStore((state) => state.prefs.language);
}
